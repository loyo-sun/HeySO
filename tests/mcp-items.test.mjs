import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createStore } from '../server/store.mjs';
import { createMcpServer } from '../server/mcp-tools.mjs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';

test('MCP creates and edits items with persistent retries, revision checks and domain rules', async t => {
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'heyso-mcp-items-'));
  t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
  const filename=path.join(dir,'workspace.json'),store=createStore(filename),server=createMcpServer(store);
  const [a,b]=InMemoryTransport.createLinkedPair(),client=new Client({name:'test',version:'1'});
  await server.connect(a);await client.connect(b);t.after(async()=>{await client.close();await server.close();});
  const invoke=async(name,args)=>{const r=await client.callTool({name,arguments:args});let data;try{data=JSON.parse(r.content[0].text);}catch{data={error:r.content[0].text};}return {error:r.isError,data};};
  const project=store.read().projects[0];
  const query=()=>invoke('query_project',{projectId:project.id});
  const args={projectId:project.id,kind:'task',title:'MCP task',description:'背景',acceptance:'可验证',startDate:project.startDate,endDate:project.endDate,expectedRevision:(await query()).data.revision,requestId:'create-one',agent:'测试 AI'};
  const created=await invoke('create_item',args);assert.equal(created.error,undefined);assert.equal(created.data.aiEnabled,false);assert.ok(created.data.number);
  assert.deepEqual((await invoke('create_item',args)).data,created.data);
  assert.equal(store.read().items.filter(i=>i.id===created.data.id).length,1);
  assert.equal(createStore(filename).read().projects[0].mcpRequests[0].result.id,created.data.id);
  assert.equal((await invoke('create_item',{...args,title:'different'})).data.status,409);
  assert.equal((await invoke('create_item',{...args,requestId:'stale'})).data.status,409);
  const edit={projectId:project.id,itemId:created.data.id,expectedRevision:(await query()).data.revision,requestId:'edit-one',agent:'测试 AI',patch:{title:'新标题',owner:'林溪',priority:'high',points:3}};
  assert.equal((await invoke('update_item',edit)).data.title,'新标题');
  assert.equal((await invoke('update_item',edit)).data.title,'新标题');
  const latest=()=>({...edit,expectedRevision:store.read().revision,requestId:crypto.randomUUID()});
  assert.equal((await invoke('update_item',{...latest(),patch:{owner:'不存在'}})).error,true);
  assert.equal((await invoke('update_item',{...latest(),patch:{startDate:'2000-01-01'}})).error,true);
  assert.equal((await invoke('update_item',{...latest(),patch:{parentId:created.data.id}})).error,true);
  assert.equal((await invoke('update_item',{...latest(),patch:{status:'done'}})).error,true);
  assert.equal((await invoke('update_item',{...latest(),patch:{aiEnabled:true}})).error,true);
  assert.equal((await invoke('update_item',{...latest(),patch:{}})).error,true);
  const child=await invoke('create_item',{...args,kind:'subtask',parentId:created.data.id,expectedRevision:store.read().revision,requestId:'child'});
  assert.equal(child.error,undefined);assert.equal(child.data.parentId,created.data.id);
  const event=store.read().events.find(e=>e.itemId===created.data.id&&e.changes?.some(c=>c.field==='title'));
  assert.equal(event.actor,'测试 AI');
  const minimalArgs={projectId:project.id,title:'仅标题 MCP 工作项',expectedRevision:store.read().revision,requestId:'minimal-create',agent:'测试 AI'};
  const minimal=await invoke('create_item',minimalArgs);assert.equal(minimal.error,undefined);assert.equal(minimal.data.kind,'story');assert.equal(minimal.data.owner,'');assert.equal(minimal.data.startDate,'');assert.deepEqual((await invoke('create_item',minimalArgs)).data,minimal.data);
  const clear=await invoke('update_item',{projectId:project.id,itemId:created.data.id,expectedRevision:store.read().revision,requestId:'clear-fields',agent:'测试 AI',patch:{owner:'',startDate:'',endDate:''}});assert.equal(clear.error,undefined);assert.equal(clear.data.endDate,'');
});
