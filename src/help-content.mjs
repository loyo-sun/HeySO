export function helpMarkdown() {
 const cell=value=>String(value).replaceAll('|','\\|').replaceAll('\n','<br>');
 const blockText=b=>b.type==='table'?'| '+b.headers.map(cell).join(' | ')+' |\n| '+b.headers.map(()=> '---').join(' | ')+' |\n'+b.rows.map(r=>'| '+r.map(cell).join(' | ')+' |').join('\n'):b.type==='steps'?b.items.map((x,i)=>`${i+1}. ${x}`).join('\n'):b.type==='list'?b.items.map(x=>'- '+x).join('\n'):b.type==='note'?`> **${b.title}**\n> ${b.text}`:b.text;
 return '# HeySO 用户帮助手册\n\n适用版本：'+helpVersion+' · 更新日期：'+helpUpdatedAt+'\n\n依据当前功能编写。页面入口、操作步骤、规则与常见问题见以下章节。\n\n## 目录\n\n'+helpArticles.map((a,i)=>`${i+1}. ${a.title}`).join('\n')+'\n\n'+helpArticles.map(a=>`## ${a.title}\n\n${a.subtitle}\n\n`+a.sections.map(s=>`### ${s.title}\n\n`+s.blocks.map(blockText).join('\n\n')).join('\n\n')).join('\n\n')+'\n';
}
